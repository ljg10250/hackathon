"""Generate ONLY raw code/name choices from the existing public snapshot. No DB writes."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
def build(jobs_path):
    jobs=json.loads(jobs_path.read_text(encoding='utf-8'))
    public=[j for j in jobs if j['quality_status']!='quarantined']
    pairs=sorted({(j['occupation_code'],j['occupation_name']) for j in public})
    assert len(public)==10743,len(public)
    assert len(pairs)==558,len(pairs)
    assert len({code for code,name in pairs})==len(pairs),'One code has multiple raw labels; review picker semantics.'
    assert all(len(code)==6 and code.isdigit() and name and '\ufffd' not in name for code,name in pairs)
    return {'source_id':'jobs','input_file':'data/processed/jobs.json','input_sha256':hashlib.sha256(jobs_path.read_bytes()).hexdigest(),'snapshot_public_job_rows':len(public),'verification_status':'raw_snapshot_labels;official_mapping_partial','notes':'공개 공고 스냅샷의 원본 직종 코드·명칭 선택 목록. 공식 매핑 완료나 관련 직종 관계를 뜻하지 않음. 실시간 DB 직종 집계가 아님.','data':[{'code':code,'name':name} for code,name in pairs]}
if __name__=='__main__':
    output=build(ROOT/'data/processed/jobs.json')
    (ROOT/'data/metadata/job_occupation_options.json').write_text(json.dumps(output,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'worker/jobOccupationOptions.ts').write_text('// Generated by scripts/build_job_options.py from an existing public snapshot.\nexport const jobOccupationOptions = '+json.dumps(output,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print(json.dumps({'public_rows':output['snapshot_public_job_rows'],'options':len(output['data'])}))
